import { getLogger } from '@logtape/logtape'
import { ResponseDeliveryError } from '../../errors'
import type { Frame } from '../frame'

const logger = getLogger(['app', 'agent', 'responseDelivery'])

export async function ResponseDelivery(frame: Frame, deps: Deps) {
  if (!frame.outbound?.text) throw new ResponseDeliveryError('Agent response not found')

  if (!frame.outbound.retrieval) {
    frame.outbound.externalId = await deps.chat.sendTextMessage({
      text: frame.outbound.text,
    })
    logger.info(`Sent text response: ${frame.outbound.text}`)
    return
  }

  const { data, mimeType, filename } = await deps.storage.retrieve(
    frame.outbound.retrieval.storageKey
  )

  if (mimeType.startsWith('image/')) {
    frame.outbound.externalId = await deps.chat.sendImageMessage({
      data,
      caption: frame.outbound.text,
    })
    logger.info(
      'Sent image response' + frame.outbound.text
        ? ` with caption: ${frame.outbound.text}`
        : ' (no caption generated by agent)'
    )
    return
  }

  if (!filename) throw new ResponseDeliveryError('Document messages require a filename')

  frame.outbound.externalId = await deps.chat.sendDocumentMessage({
    data,
    caption: frame.outbound.text,
    filename,
  })
  logger.info(
    `Sent document response: ${
      frame.outbound.text ? `Caption: ${frame.outbound.text}` : 'No caption'
    }`
  )
}
